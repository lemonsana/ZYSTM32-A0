/* ---------------------------------------------------------------------------
 *  传感器接口选择：
 *      1 = I2C（默认）—— 与"可循迹版本"一致，已验证可用
 *      0 = 串行 CLK/DAT —— v2.2 方案，模块接线见下
 * ------------------------------------------------------------------------- */
#define GRAY_IF_I2C          1

/* ---------------------------------------------------------------------------
 *  模拟量极性（本车实测与原厂参考版本的关键差异）
 *  ---------------------------------------------------------------------------
 *  全工程只认一个约定：白≈255、黑≈0（"越黑数值越小"）。权重、丢线判据、
 *  GRAY_BLACK_CUTOFF、融合模式的 Gray_IsOnLine() 都建立在这个约定上。
 *
 *      0 = 原厂/可循迹版本：白≈255，黑≈0
 *      1 = 本车实测：指示灯暗的部分是黑线，模拟量反而大（黑≈255，白≈0）
 *
 *  置 1 时在 gray_iface_read() 出口统一做 255-v 反相，改回"白 255 / 黑 0"，
 *  下游一行都不用动、参数也不用重调。若实测黑白读数不是接近 0/255 两端，
 *  先打印 Gray_ReadRaw() 的 8 路裸值确认范围再决定。
 * ------------------------------------------------------------------------- */
#define GRAY_ANALOG_INVERT   1

/* ============================ I2C 接线 ============================
 *      模块 VCC   →  5V
 *      模块 GND   →  GND
 *      模块 SCL   →  PB10（丝印 IO16）
 *      模块 SDA   →  PB11（丝印 IO15）
 *      模块 PULL 跳线 → 必须短接（5V 上拉）
 *      模块 AD0/AD1   → 不装（保持默认地址 0x4C）
 *  PB10/PB11 是 5V 容忍脚，5V 上拉安全。
 * ================================================================= */
#define GRAY_I2C_GPIO         GPIOB
#define GRAY_I2C_SCL_PIN      GPIO_Pin_10
#define GRAY_I2C_SDA_PIN      GPIO_Pin_11
#define GRAY_I2C_ADDR         0x4C

/* 感为寄存器 */
#define GW_GRAY_PING          0xAA
#define GW_GRAY_PING_OK       0x66
#define GW_GRAY_ANALOG_MODE   0xB0    /* 0xB0~0xB7：8 路模拟量 */
#define GW_GRAY_CHANNEL_EN    0xCE    /* 通道使能 */
#define GW_GRAY_NORMALIZE     0xCF    /* 归一化使能 */

/* ============================ 串行接线（备选） ============================
 *      模块 VCC   →  5V
 *      模块 GND   →  GND
 *      模块 CLK   →  PB10（单片机输出时钟）
 *      模块 DAT   →  PB11（模块输出数据，5V 容忍脚）
 *  时序：CLK 拉低 → 2us → 读DAT → CLK 拉高 → 5us，循环 8 次，bit0 先出
 * ======================================================================= */
#define GRAY_CLK_PIN          GPIO_Pin_10
#define GRAY_CLK_GPIO         GPIOB
#define GRAY_DAT_PIN          GPIO_Pin_11
#define GRAY_DAT_GPIO         GPIOB

/* ============================================================================
 *  循迹参数（调车就改这一段，改完重新编译烧录）
 *  ----------------------------------------------------------------------------
 *  控制链路（自下而上理解，调参时对号入座）：
 *
 *    8 路归一化模拟量 (白≈255 黑≈0)
 *        │
 *        │ ① 加权重心：wᵢ = CUTOFF − 值ᵢ（越黑权重越大），posᵢ = ±7,±5,±3,±1
 *        │    error = Σ(wᵢ·posᵢ) / (Σwᵢ·7) × 100      → 范围 −100 ~ +100
 *        │    0 = 线在正中；负数 = 线偏左；正数 = 线偏右
 *        ▼
 *    ┌──────────────────────────────────────────────────────────────┐
 *    │ ② 一阶低通：filt = (filt×3 + error)/4     （抑制单帧跳变）    │
 *    │ ③ 死区：|filt| < DEADBAND → 0             （中线附近不抖）    │
 *    │ ④ PID：                                                      │
 *    │      P = e × GAIN / 100                                      │
 *    │      I = (Σ e×帧时长) × KI / 1000                            │
 *    │      D = (e − e上一帧) × KD / 100                            │
 *    │      correction = P + I + D                                  │
 *    │ ⑤ 速度调度：base = BASE − |e|×SLOW_GAIN/100 − |Δe|×SLOW_D_GAIN/100 │
 *    │ ⑥ 输出：左 = base + correction，右 = base − correction         │
 *    │    限幅：左/右 ∈ [−INNER_REVERSE, 95]                        │
 *    └──────────────────────────────────────────────────────────────┘
 *
 *  ----------------------------------------------------------------------------
 *  【P 项】GRAY_STEER_GAIN / GRAY_STEER_GAIN_FAR / GRAY_FAR_THRESHOLD
 *      P 是"看到多大偏差就打多大方向"。
 *      · 直线画龙（左右摆）      → 调小 GAIN（32 → 25）
 *      · 弯道切不进去/转向不足    → 调大 GAIN（32 → 40）
 *      GAIN_FAR 是"大误差专用"的档位，|e| 超过 FAR_THRESHOLD 时启用，
 *      用来在不牺牲直线稳定性的前提下，让急弯打得更狠。
 *      只调一个的话：先动 GAIN，弯里不够再动 GAIN_FAR。
 *
 *  【D 项】GRAY_KD
 *      D 是"看到偏差变化多快就提前收手"，起阻尼作用。
 *      · 进弯冲过头、出弯甩尾    → 调大 KD（12 → 20）
 *      · 车发抖、电机嗡嗡响       → 调小 KD（12 → 6 或 0）
 *      本工程误差已过一阶低通，D 不会太吵，但别一次加太多。
 *
 *  【I 项】GRAY_KI / GRAY_I_LIMIT
 *      I 是"偏差长期存在就持续加力"，用来消静差。
 *      · 车总贴着线的一侧跑、回不到正中 → 加 KI（0 → 2 → 4）
 *      · 前视 12cm 时**建议保持 0**：探头看得远，积分容易攒成过冲
 *      I_LIMIT 是积分上限，防止长时间堵转后"甩不回来"。
 *
 *  【速度调度】GRAY_SLOW_GAIN / GRAY_SLOW_D_GAIN / GRAY_MIN_SPEED
 *      base 会随偏差和偏差变化率自动降速：
 *      · 弯里冲出去                → 调大 SLOW_GAIN / SLOW_D_GAIN
 *      · 整体太慢、过弯磨蹭        → 调小 SLOW_GAIN，或调大 MIN_SPEED
 *
 *  【转弯极限】GRAY_INNER_REVERSE
 *      内轮允许反转的最大幅度，急弯时"原地搓"能显著减小转弯半径。
 *      · 急弯拐不过来              → 45 → 60
 *      · 弯里车尾扫、轮胎打滑      → 45 → 30
 *
 *  【丢线找回】GRAY_LOST_SPIN_SPEED / GRAY_LOST_STOP_MS
 *      · 掉线后找不回来            → 速度调大、时间调长
 *      · 掉线后乱转圈              → 速度调小
 *
 *  【几何前提】GRAY_LOOKAHEAD_CM
 *      灰度板到驱动轴的距离。前视 L、阵列半宽 h 时，能连续跟住的最小弯半径
 *      R ≈ L²/(2h)。本车 L=12cm、h≈3.5cm → R ≈ 20.6cm，更急的弯必然丢线，
 *      此时靠"丢线 → 原地找回"兜底，属于正常现象。
 * ============================================================================ */
#define GRAY_LOOKAHEAD_CM      12   /* 灰度板到电机驱动轴的距离（仅说明/换算用） */

#define GRAY_BASE_SPEED        60   /* 直行基础速度（先在 60 跑顺，再试 70/80，最高 95） */
#define GRAY_STEER_GAIN        40   /* P：小误差增益 */
#define GRAY_STEER_GAIN_FAR    60   /* P：大误差（急弯）增益 */
#define GRAY_FAR_THRESHOLD     30   /* |误差| 超过它切换到 FAR 增益 */
#define GRAY_KI                 0   /* I：积分增益（前视 12cm 建议 0） */
#define GRAY_KD                12   /* D：微分增益 */
#define GRAY_I_LIMIT         2500   /* 积分上限（误差·毫秒） */
#define GRAY_BLACK_CUTOFF     180   /* 低于此值算黑线（白≈255 黑≈0） */
#define GRAY_CENTER_DEADBAND    2   /* 误差死区 */
#define GRAY_CHANNEL_MIRROR     0   /* 1 = 镜像探头顺序（方向反了改这个） */

#define GRAY_SLOW_GAIN         20   /* 速度调度：按 |误差| 降速 */
#define GRAY_SLOW_D_GAIN       40   /* 速度调度：按 |误差变化| 降速（进弯预减速） */
#define GRAY_MIN_SPEED         25   /* 降速下限 */
#define GRAY_INNER_REVERSE     45   /* 内轮允许反转的最大幅度 */

/* ============================================================================
 *  转向量归一化 + 速度补偿（R2.1，高速过弯）
 *  ----------------------------------------------------------------------------
 *  问题：黑线实际只有 3~4 路宽。线压在阵列边缘时，加权重心只能算出 55~70
 *        的误差（8 路全黑才是 0，单路贴边才是 100）。原来按 100 归一化，
 *        "线已经到头"也只输出一半多一点的转向量 —— 60 速以上内侧轮压不到 0，
 *        车被推着往外走，最后冲出黑线。
 *
 *  做法：把 P/I/D 合出来的 correction 再乘一个系数
 *            k = (100 / FULL) × (base / REF)
 *        ① 100/FULL：把"线到边缘(55~70)"放大成接近满舵；
 *        ② base/REF：转同样半径所需的左右差速与车速成正比 —— 高速多打、低速少打。
 *        两项合起来，正好让"误差到 FULL 时内侧轮刚好停转"，且与车速无关。
 *
 *  调参：
 *      GRAY_STEER_FULL_ERROR  50 → 更早满舵（更凶）；65 → 更温和
 *      GRAY_STEER_REF_SPEED   调大 = 同样车速下补偿变小（整体更柔）
 *      GRAY_STEER_GAIN_MAX    补偿上限；**设成 100 就完全关掉补偿、退回老行为**
 * ============================================================================ */
#define GRAY_STEER_FULL_ERROR   55   /* |误差| 到这里算"满舵"（≈4 路宽的黑线压到边缘） */
#define GRAY_STEER_REF_SPEED    60   /* 标定速度：base=60 时倍率为 1.0 */
#define GRAY_STEER_GAIN_MAX    300   /* 总倍率上限(%)：300 = 最多放大到 3 倍 */

#define GRAY_LOST_SPIN_SPEED   50   /* 丢线找线速度 */
#define GRAY_LOST_STOP_MS    3000
#define GRAY_FRAME_MS          10

/* ============================================================================
 *  V6 新增：加速斜坡 / 覆盖度（线宽）判别 / 事件确认
 *  ----------------------------------------------------------------------------
 *  【加速斜坡】GRAY_RAMP_ALPHA
 *      只作用在"基础速度"上，不碰差速修正量：
 *          base_ramp += (base_target - base_ramp) × ALPHA / 1000   （每 10ms 一次）
 *      所以急弯里内轮该反转还是立刻反转，不会因为斜坡而转不动；
 *      但模式切换、找回线之后车是"缓加速"而不是阶跃，轮胎不打滑、不甩尾。
 *      ALPHA 越大越接近阶跃：120 ≈ 80ms 时间常数；300 ≈ 30ms；1000 = 关闭斜坡。
 *
 *  【覆盖度判别】GRAY_WIDE_MIN_ACTIVE
 *      加权重心对称（权重 ±7±5±3±1），所以 8 路全黑时 error 恒等于 0，和"正常
 *      压在 2cm 黑线上"完全无法区分。这里改用"几路压线"来区分：
 *          正常 2cm 黑线 → 2~4 路
 *          十字 / 宽黑带 / 停车线 → 5 路以上，通常 7~8 路
 *      压线数 >= WIDE_MIN_ACTIVE 就判 EV_WIDE。设成 9 等于关闭该功能。
 *
 *  【事件确认】WIDE_CONFIRM / LOST_CONFIRM
 *      连续 N 帧都满足才切换事件（去抖/滞回）。N=1 表示不确认。
 *
 *  【宽黑停车】GRAY_WIDE_STOP_MS
 *      EV_WIDE 持续超过这么久 → 停车（终点黑区 / 停车线用）。0 = 不停车，只计数。
 * ========================================================================== */
#define GRAY_RAMP_ALPHA         120   /* 斜坡系数 /1000，1000 = 关闭 */
#define GRAY_WIDE_MIN_ACTIVE      7   /* 几路压线算"宽黑"，9 = 关闭 */
#define GRAY_WIDE_CONFIRM         3   /* 宽黑连续多少帧确认 */
#define GRAY_LOST_CONFIRM         3   /* 丢线连续多少帧确认 */
#define GRAY_WIDE_STOP_MS         0   /* 宽黑持续多久停车(ms)，0 = 不停车 */

/* ============================================================================
 *  V7 新增：十字路口"默认直行"
 *  ----------------------------------------------------------------------------
 *  只有"几路压线"是不够的：很多赛道的十字中间是断线（贴纸拼的），车开上去
 *  一两帧就变回"丢线"，于是走 EV_LOST 原地找线 —— 这就是"过不了十字"的真相。
 *
 *  这里做三件事：
 *    1) 进 EV_WIDE 的瞬间用陀螺锁存航向 yaw_hold；
 *    2) 宽黑期间不走 PID，改用 heading 修正（yaw_hold - 当前 yaw）走直线；
 *    3) 出宽黑后的 GRAY_COAST_MS 内如果又丢线，**继续按航向直行**，
 *       等这段"保护时间"过了才允许原地找线 —— 十字中间的缝就这么过去。
 *
 *  没有陀螺（Imu_IsReady()==0）时自动退化成"误差锁 0 直行"，行为和 V6 一样。
 * ========================================================================== */
#define GRAY_CROSS_KP            30   /* 航向修正：每 0.1° 偏差给 0.3 个速度单位 */
#define GRAY_CROSS_DEAD          10   /* 航向死区（0.1°），10 = 1.0° 内不修正 */
#define GRAY_COAST_MS           250   /* 过完宽黑后的"继续直行"保护时间(ms) */

/* ============================================================================
 *  事件枚举（V6）
 *  ----------------------------------------------------------------------------
 *  把"看到什么"和"怎么打方向"分开：
 *      采样层   gray_read_frame()  → error(位置) + active(几路压线)
 *      事件层   gray_update_event()→ LINE / WIDE / LOST（带去抖）
 *      决策层   SearchRun() 里 switch(event) —— 决定这一帧"走不走 PID"
 *      控制层   PID + 斜坡 + 输出
 *  这样十字、停车线、丢线都成了"明确的事件"，而不是靠一堆 if 藏在 PID 里。
 * ========================================================================== */
typedef enum
{
    GRAY_EV_NONE = 0,       /* 还没采样 */
    GRAY_EV_LINE,           /* 正常压线（2~4 路） */
    GRAY_EV_WIDE,           /* 宽黑：十字 / 横黑带 / 停车线（>=WIDE_MIN_ACTIVE 路） */
    GRAY_EV_LOST            /* 丢线：一路都没压到 */
} gray_event_t;

