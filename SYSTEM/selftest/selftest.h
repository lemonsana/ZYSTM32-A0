#ifndef __SELFTEST_H_
#define __SELFTEST_H_

#include "stm32f10x.h"
#include "app_mode.h"

/* ============================================================================
 *  自检模式（模式 4）  V6
 *  ----------------------------------------------------------------------------
 *  思路抄自 TC387 工程里那排 "Test_xxx()" 函数 + 主函数里标着 PASS 的注释：
 *  上车前不再靠"串口 ready=1 然后猜"，而是让车自己把每个外设点一遍名。
 *
 *  依次检查：
 *      1. 灰度   I2C 读 5 帧，打印 8 路裸值 + 覆盖度
 *      2. 电机   左轮 / 右轮 / 双轮 各转 600ms（看轮子，听声音）
 *      3. 舵机   170° → 10° → 90°（看舵机是否扫到位）
 *      4. 超声波  连测 3 次（手挡在前面，看数值跳不跳）
 *      5. 按键   PC2 按一下（4 秒超时）
 *      6. 遥控   遥控器任意键（4 秒超时）
 *      7. 参数   打印当前参数与 Flash 状态
 *      8. 汇总   PASS / FAIL 列表
 *
 *  退出：按 PC2 切到下一个模式（或串口发 '1'/'2'/'3'）。
 * ========================================================================== */

void SelfTest_Start(void);
app_task_result_t SelfTest_Update(void);
void SelfTest_Stop(void);

#endif
